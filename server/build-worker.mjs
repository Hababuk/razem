// Bundles recur.js + core.mjs + runner.mjs + worker-entry.mjs into one file to paste into Cloudflare.
// Run:  node server/build-worker.mjs   → server/cloudflare-worker.js
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
const parts = [['../recur.js', false], ['core.mjs', false], ['runner.mjs', false], ['worker-entry.mjs', true]];
let out = `// Razem reminders — Cloudflare Worker. GENERATED by server/build-worker.mjs from recur.js, core.mjs, runner.mjs, worker-entry.mjs.\n// Secrets: FIREBASE_SERVICE_ACCOUNT, VAPID_PUBLIC, VAPID_PRIVATE, VAPID_SUBJECT, RUN_TOKEN. Trigger: cron "*/2 * * * *".\n`;
for (const [f, keepDefault] of parts) {
  let s = readFileSync(new URL(f, here), 'utf8');
  s = s.replace(/^import[^;]+;\s*$/gm, '');                       // everything lives in one scope now
  s = s.replace(/^export (?!default)/gm, '');                     // drop named exports
  if (!keepDefault) s = s.replace(/^export default/gm, 'const _unused =');
  out += `\n// ===== ${f} =====\n${s}`;
}
writeFileSync(new URL('cloudflare-worker.js', here), out);
console.log('wrote server/cloudflare-worker.js', out.length, 'bytes');
